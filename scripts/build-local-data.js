const fs = require('fs');
const path = require('path');

// Classic scripts can load beside file:// pages, unlike fetch of local JSON.
const root = path.join(__dirname, '..');
const files = ['data.json', 'changelog.json', 'identityUpdates.json', 'egoData.json', 'egoGiftData.json', 'decks.json', 'deckKeywords.json'];
const data = Object.fromEntries(files.map(file => [file, JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'))]));
fs.writeFileSync(path.join(root, 'local-data.js'), `// Generated by scripts/build-local-data.js. Do not edit.\nwindow.LIMQUIZ_LOCAL_DATA = ${JSON.stringify(data)};\n`, 'utf8');
console.log(`✓ local-data.js 생성 완료: ${files.length}개 데이터 파일`);
