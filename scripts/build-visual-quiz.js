const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'visualQuizData.json'), 'utf8'));
for (const mode of ['character', 'boss', 'panic']) {
  if (!Array.isArray(data[mode]) || !data[mode].length) throw new Error(`Empty visual quiz: ${mode}`);
  const ids = new Set();
  for (const row of data[mode]) {
    if (!row.id || ids.has(row.id) || !row.name || !Number.isInteger(row.chapter) || !Array.isArray(row.aliases) || !Array.isArray(row.hints)) throw new Error(`Invalid visual quiz entry: ${row.id}`);
    if (!/^images\/visual-quiz\/[\w-]+\.webp$/.test(row.image) || !fs.existsSync(path.join(root, row.image))) throw new Error(`Missing visual quiz image: ${row.image}`);
    ids.add(row.id);
  }
}
fs.writeFileSync(path.join(root, 'visualQuizData.js'), `// Generated by scripts/build-visual-quiz.js.\nwindow.LIMQUIZ_VISUAL_DATA = ${JSON.stringify(data)};\n`);
console.log('✓ 이미지 퀴즈 데이터 생성 완료');
